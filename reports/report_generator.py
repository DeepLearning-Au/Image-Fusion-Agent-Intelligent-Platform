def generate_report(result: dict, user_note: str = "") -> str:
    metrics = result["metrics"]

    metric_rows = "\n".join(
        [f"| {k} | {v:.4f} |" for k, v in metrics.items()]
    )

    score = metrics.get("综合质量评分", 0)

    if score >= 85:
        level = "优秀"
        conclusion = "融合结果整体质量较高，结构边界、纹理细节和跨模态信息保留较好。"
    elif score >= 70:
        level = "良好"
        conclusion = "融合结果整体可用，能够较好保留源图像主要结构和纹理信息，但局部区域仍可能存在细节不足或轻微结构漂移。"
    else:
        level = "一般"
        conclusion = "融合结果仍有优化空间，建议重点检查红外—可见光配准、输入图像质量和模型对高频边缘的约束能力。"

    report = f"""# MambaDFuse 红外—可见光图像融合智能分析报告

## 1. 任务说明

本次任务基于本地 MambaDFuse 模型，对输入的可见光图像与红外图像进行多模态融合推理，并自动完成质量评价、边缘对比和结果分析。

用户备注：

{user_note if user_note else "无"}

## 2. 模型信息

| 项目 | 内容 |
|---|---|
| 模型名称 | {result["model_name"]} |
| 输入模态 | 可见光灰度/Y通道 + 红外灰度图 |
| 核心机制 | DWT/IDWT小波分解重构、HME混合模态增强、DAG-MF差异感知Mamba融合、A3F自适应融合 |
| 推理设备 | {result["device"]} |
| 推理耗时 | {result["elapsed_seconds"]:.2f} s |

## 3. 输入与输出

- 可见光图像：`{result["optical_path"]}`
- 红外图像：`{result["sar_path"]}`
- 灰度融合图：`{result["fused_gray_path"]}`
- 彩色融合图：`{result["fused_color_path"]}`
- 可见光边缘图：`{result["edge_optical_path"]}`
- 红外边缘图：`{result["edge_sar_path"]}`
- 融合边缘图：`{result["edge_fused_path"]}`
- 跨模态差异图：`{result["diff_path"]}`

## 4. 融合质量评价指标

| 指标 | 数值 |
|---|---:|
{metric_rows}

## 5. 自动分析结论

系统综合评分为 **{score:.2f}/100**，融合质量等级为 **{level}**。

{conclusion}

从指标角度看：

- **EN 信息熵** 反映融合图像的信息丰富度；
- **SD 标准差** 反映图像对比度；
- **SF 空间频率** 和 **AG 平均梯度** 反映纹理细节与边缘清晰度；
- **MI 互信息** 反映融合图像对可见光图像和红外图像信息的保留能力；
- **Qabf 边缘保持指标** 反映融合图像对源图像边缘结构的继承能力；
- **SSIM** 反映融合图像与源图像之间的结构相似性。

## 6. 可能问题诊断

如果融合图局部出现边缘模糊、纹理错配或结构漂移，可能原因包括：

1. 可见光图像与红外图像存在配准误差；
2. 红外图像噪声、非均匀性或动态范围处理影响融合；
3. 模型对复杂地物边界或小目标区域的结构约束不足；
4. 可见光图像受阴影、低照度或亮度变化影响，导致纹理信息不稳定。

## 7. 改进建议

1. 在推理前增加红外—可见光图像配准检查；
2. 根据红外传感器特性选择非均匀性校正或轻量去噪；
3. 在训练阶段增加边缘保持损失、结构一致性损失或频域约束；
4. 对复杂边界、小目标和强散射区域建立困难样本集；
5. 将本次融合结果、指标和人工评价写入知识库，用于后续RAG智能分析。

## 8. 工程应用价值

该系统将本地改进版 WEMFusion 模型封装为可调用工具，实现了从图像输入、模型推理、质量评价、边缘对比到报告生成的完整闭环，可用于遥感图像智能解译、雷达图像分析、外场测试辅助和企业研发报告生成。
"""

    return report
